"""Генератор SQL DDL (`schema.sql`)."""

from __future__ import annotations

from eggpipe import Artifact, FieldDef, ModelSlice, generator
from eggpipe_reference_generators._common import (
    primitive_type,
    snake_case,
    sorted_entities,
)

_HEADER = "-- Generated by eggpipe. Do not edit."

_SQL_TYPES = {
    "string": "VARCHAR(255)",
    "text": "TEXT",
    "integer": "INTEGER",
    "bigint": "BIGINT",
    "boolean": "BOOLEAN",
    "float": "DOUBLE PRECISION",
    "date": "DATE",
    "datetime": "TIMESTAMP",
    "uuid": "UUID",
    "json": "JSONB",
}


@generator(
    id="sql",
    name="SQL DDL",
    input_formats={"entity-model"},
    output_scope="model",
)
def sql_generator(model: ModelSlice) -> list[Artifact]:
    """Сгенерировать `schema.sql`: CREATE TABLE на сущность, snake_case имена."""
    lines = [_HEADER]
    for entity in sorted_entities(model):
        columns = [_column(field, model) for field in entity.fields]
        if not columns:
            # Пустая сущность не даёт валидного DDL.
            continue
        lines.extend(["", f"CREATE TABLE {snake_case(entity.name)} ("])
        lines.append(",\n".join(columns))
        lines.append(");")
    return [Artifact(path="schema.sql", content="\n".join(lines) + "\n")]


def _column(field: FieldDef, model: ModelSlice) -> str:
    name = snake_case(field.name)
    sql_type = _SQL_TYPES[primitive_type(field.type, model)]
    required = " NOT NULL" if field.required else ""
    return f"    {name} {sql_type}{required}"


__all__ = ["sql_generator"]
