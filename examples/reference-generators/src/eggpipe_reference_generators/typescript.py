"""Генератор TypeScript-интерфейсов (`models.ts`)."""

from __future__ import annotations

from eggpipe import Artifact, FieldDef, ModelSlice, generator
from eggpipe_reference_generators._common import (
    camel_case,
    pascal_case,
    primitive_type,
    sorted_entities,
)

_HEADER = "// Generated by eggpipe. Do not edit."

_TS_TYPES = {
    "string": "string",
    "text": "string",
    "integer": "number",
    "bigint": "number",
    "boolean": "boolean",
    "float": "number",
    "date": "string",
    "datetime": "string",
    "uuid": "string",
    "json": "Record<string, unknown>",
}


@generator(
    id="typescript",
    name="TypeScript Models",
    input_formats={"entity-model"},
    output_scope="model",
)
def typescript_generator(model: ModelSlice) -> list[Artifact]:
    """Сгенерировать `models.ts` с interface на сущность."""
    lines = [_HEADER]
    for entity in sorted_entities(model):
        lines.extend(["", f"export interface {pascal_case(entity.name)} {{"])
        lines.extend(f"  {_field_line(field, model)}" for field in entity.fields)
        lines.append("}")
    return [Artifact(path="models.ts", content="\n".join(lines) + "\n")]


def _field_line(field: FieldDef, model: ModelSlice) -> str:
    base = _TS_TYPES[primitive_type(field.type, model)]
    annotation = f"{base} | null" if field.nullable else base
    optional = "?" if not field.required else ""
    return f"{camel_case(field.name)}{optional}: {annotation};"


__all__ = ["typescript_generator"]
