"""Pydantic v2 models generator (`models.py`)."""

from __future__ import annotations

from eggpipe import Artifact, FieldDef, ModelSlice, generator
from eggpipe_reference_generators._common import (
    pascal_case,
    primitive_type,
    snake_case,
    sorted_entities,
)

_HEADER = "# Generated by eggpipe. Do not edit."

_PYDANTIC_TYPES = {
    "string": "str",
    "text": "str",
    "integer": "int",
    "bigint": "int",
    "boolean": "bool",
    "float": "float",
    "date": "date",
    "datetime": "datetime",
    "uuid": "str",
    "json": "dict[str, Any]",
}

_DATETIME_TYPES = {"date", "datetime"}


@generator(
    id="pydantic",
    name="Pydantic Models",
    input_formats={"entity-model"},
)
def pydantic_generator(model: ModelSlice) -> list[Artifact]:
    """Generate `models.py` with one BaseModel per entity."""
    entities = sorted_entities(model)
    used = {primitive_type(field.type, model) for entity in entities for field in entity.fields}

    lines = [_HEADER, "", "from __future__ import annotations"]
    if used & _DATETIME_TYPES:
        imports = ", ".join(sorted(used & _DATETIME_TYPES))
        lines.append(f"from datetime import {imports}")
    if "json" in used:
        lines.append("from typing import Any")
    lines.extend(["", "from pydantic import BaseModel"])

    for entity in entities:
        lines.extend(["", "", f"class {pascal_case(entity.name)}(BaseModel):"])
        if not entity.fields:
            lines.append("    pass")
            continue
        lines.extend(f"    {_field_line(field, model)}" for field in entity.fields)

    return [Artifact(path="models.py", content="\n".join(lines) + "\n")]


def _field_line(field: FieldDef, model: ModelSlice) -> str:
    base = _PYDANTIC_TYPES[primitive_type(field.type, model)]
    annotation = f"{base} | None" if field.nullable or not field.required else base
    default = "" if field.required else " = None"
    return f"{snake_case(field.name)}: {annotation}{default}"


__all__ = ["pydantic_generator"]
